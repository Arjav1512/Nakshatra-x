/**
 * Mine telemetry endpoint.
 *
 * Integrity contract (see docs/INTEGRITY.md):
 *   - Weather is MEASURED from Open-Meteo when the call succeeds; on failure the
 *     response degrades to SYNTHETIC and says so.
 *   - Operational figures (downtime, blasting readiness, production rates) are
 *     SYNTHETIC — MOIL operational data is proprietary. They are generated by a
 *     seeded model so identical requests return identical values.
 *   - Risk and shortfall are DERIVED: an explicit, documented arithmetic model
 *     over the inputs above. The attribution returned is an exact additive
 *     decomposition of that model — it is not SHAP and is not labelled as such.
 *   - Scene metadata is a real STAC query against Earth Search. If the query
 *     fails the list is empty; scene identifiers are never fabricated.
 */

