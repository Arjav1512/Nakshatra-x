/**
 * The stack is read from disk on the server, so its 1,710 marks are in the HTML
 * rather than appearing after hydration. Generated by
 * `python -m app.ml.export_stack` from the loaded honest model; 75 KB.
 */
async function loadStack(): Promise<StackData | null> {
  try {
    const file = path.join(process.cwd(), 'public', 'data', 'prospectivity-stack.json')
    return JSON.parse(await readFile(file, 'utf8')) as StackData
  } catch {
    return null
  }
}

